function formatNumber(value) {
  if (typeof value !== 'number' || !Number.isFinite(value)) {
    return '待补';
  }

  const abs = Math.abs(value);
  let maximumFractionDigits = 2;

  if (abs >= 1000) {
    maximumFractionDigits = 0;
  } else if (abs >= 100) {
    maximumFractionDigits = 1;
  } else if (abs >= 1) {
    maximumFractionDigits = 2;
  } else {
    maximumFractionDigits = 3;
  }

  return value.toLocaleString('en-US', {
    minimumFractionDigits: 0,
    maximumFractionDigits,
  });
}

function formatPercent(value) {
  if (typeof value !== 'number' || !Number.isFinite(value)) {
    return '待补';
  }

  return `${value >= 0 ? '+' : ''}${value.toFixed(1)}%`;
}

function buildAnnualFinance({
  periodLabel,
  unit,
  revenue,
  netProfit,
  grossMargin,
  forwardPE,
  display = {},
  note,
  flags = {},
}) {
  return {
    schemaVersion: 1,
    datasetKind: 'annual',
    periodLabel,
    periods: periodLabel.split('/').map((label) => label.trim()),
    unit,
    series: {
      revenue,
      netProfit,
      grossMargin,
      forwardPE,
    },
    display: {
      revenue: display.revenue || revenue.map(formatNumber),
      netProfit: display.netProfit || netProfit.map(formatNumber),
      grossMargin: display.grossMargin || grossMargin.map(formatPercent),
      forwardPE: display.forwardPE || forwardPE.map(() => '待补'),
    },
    flags,
    note,
    sourcePath: SOURCE_PATH,
  };
}

